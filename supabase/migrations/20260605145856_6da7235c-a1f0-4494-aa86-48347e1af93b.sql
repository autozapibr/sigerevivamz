-- Trigger for updated_at
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_education_level_fees_updated_at
BEFORE UPDATE ON public.education_level_fees
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

CREATE TRIGGER tr_enrollment_periods_updated_at
BEFORE UPDATE ON public.enrollment_periods
FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();
