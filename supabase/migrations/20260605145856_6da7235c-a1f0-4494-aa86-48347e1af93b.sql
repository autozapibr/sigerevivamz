ON CONFLICT (name) DO NOTHING;

-- Create education_level_fees table
CREATE TABLE IF NOT EXISTS public.education_level_fees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    education_level_id BIGINT REFERENCES public.education_levels(id) ON DELETE CASCADE,
    academic_year_id BIGINT REFERENCES public.academic_years(id) ON DELETE CASCADE,
    enrollment_fee NUMERIC(15,2) NOT NULL DEFAULT 0,
    monthly_fee NUMERIC(15,2) NOT NULL DEFAULT 0,
    re_enrollment_fee NUMERIC(15,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    UNIQUE(education_level_id, academic_year_id)
);

-- Create enrollment_periods table
CREATE TABLE IF NOT EXISTS public.enrollment_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id BIGINT REFERENCES public.academic_years(id) ON DELETE CASCADE,
    education_level_id BIGINT REFERENCES public.education_levels(id) ON DELETE CASCADE,
    type enrollment_type NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

