function cleanContent(raw: string): string {
  let cleaned = raw
    .replace(/^```html\s*/i, '')
    .replace(/^```\w*\s*/gm, '')
    .replace(/```\s*$/gm, '')
    .trim();

  // Remove any AI-generated <h1> titles
  cleaned = cleaned.replace(/<h1[^>]*>[\s\S]*?<\/h1>/gi, '');

  // Remove duplicated header-info blocks generated by AI
  cleaned = cleaned.replace(/<div[^>]*class="header-info"[^>]*>[\s\S]*?<\/div>/gi, '');

  // Remove any "INFORMAÇÕES GERAIS" section entirely (h2 + following list/paragraph until next h2)
  cleaned = cleaned.replace(/<h2[^>]*>\s*(?:📌\s*)?INFORMA[ÇC][ÕO]ES\s+GERAIS\s*<\/h2>[\s\S]*?(?=<h2)/gi, '');

  // Remove any block containing school/professor/class/discipline info within first 2000 chars
  const first2000 = cleaned.substring(0, 2000);
  const rest = cleaned.substring(2000);
  const cleanedFirst = first2000
    .replace(/<(?:div|table|section|header|ul)[^>]*>[\s\S]*?(?:Escola\s*:|Professor\s*:|Turma\s*:|Classe\s*:|Disciplina\s*:|Data\s+das?\s+Aulas?\s*:)[\s\S]*?<\/(?:div|table|section|header|ul)>/gi, '')
    .replace(/<p[^>]*>[\s\S]*?(?:Escola\s*:|Professor\s*:|Turma\s*:|Classe\/Turma\s*:|Disciplina\s*:)[\s\S]*?<\/p>/gi, '')
    // Remove standalone list items with professor/turma/disciplina info
    .replace(/<li[^>]*>[\s\S]*?(?:Professor\s*:|Turma\s*:|Classe\s*:|Disciplina\s*:|Data\s+das?\s+Aulas?\s*:|Tema\s*:|Princ[ií]pios?\s+da\s+AEP)[\s\S]*?<\/li>/gi, '')
    // Remove any orphaned <ul> that became empty after removing <li>
    .replace(/<ul[^>]*>\s*<\/ul>/gi, '');
  cleaned = cleanedFirst + rest;

  return cleaned.trim();
}

