function cleanContent(raw: string): string {
  let cleaned = raw
    .replace(/^```html\s*/i, '')
    .replace(/^```\w*\s*/gm, '')
    .replace(/```\s*$/gm, '')
    .trim();

  // Remove any AI-generated <h1> titles (the header is in the UI component)
  cleaned = cleaned.replace(/<h1[^>]*>[\s\S]*?<\/h1>/gi, '');

  // Remove duplicated header-info blocks generated by AI
  cleaned = cleaned.replace(/<div[^>]*class="header-info"[^>]*>[\s\S]*?<\/div>/gi, '');

  // Remove any block (div, table, p, section, header) containing school/professor/class/discipline info
  // within the first 1500 chars to avoid stripping legitimate content deeper in the document
  const first1500 = cleaned.substring(0, 1500);
  const rest = cleaned.substring(1500);
  const cleanedFirst = first1500
    .replace(/<(?:div|table|section|header)[^>]*>[\s\S]*?(?:Escola\s*:|Professor\s*:|Turma\s*:|Classe\s*:|Disciplina\s*:)[\s\S]*?<\/(?:div|table|section|header)>/gi, '')
    .replace(/<p[^>]*>[\s\S]*?(?:Escola\s*:|Professor\s*:|Turma\s*:|Classe\/Turma\s*:|Disciplina\s*:)[\s\S]*?<\/p>/gi, '');
  cleaned = cleanedFirst + rest;

  return cleaned.trim();
}

