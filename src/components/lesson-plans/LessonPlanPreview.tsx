export function LessonPlanPreview({ content, onSave, onClose, isSaving, isSaved = false, teacherName = '', className = '', subjectName = '' }: LessonPlanPreviewProps) {
  const [showCloseConfirm, setShowCloseConfirm] = useState(false);
  const [isDownloading, setIsDownloading] = useState(false);

  const cleaned = cleanContent(content);
  const sanitizedContent = DOMPurify.sanitize(cleaned);

  const dateOnly = new Date().toLocaleDateString('pt-MZ', { day: '2-digit', month: '2-digit', year: 'numeric' });
  const dateTime = new Date().toLocaleString('pt-MZ', { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' });

  const getFullHtml = () => `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8" />
<title>Plano de Aula AEP - Escola Reviva</title>
<style>${A4_STYLES}</style>
</head>
<body>
  <div class="running-footer">
    <span>SiGER - Sistema de Gestão Escolar Reviva</span>
    <span>${dateOnly}</span>
  </div>

  <main class="content">
    ${getHeaderHtml(teacherName, className, subjectName)}
    ${sanitizedContent}
  </main>
</body>
</html>`;

  const handlePrint = () => {
    const printWindow = window.open('', '_blank');
    if (!printWindow) {
      toast({ title: 'Erro', description: 'Permita pop-ups para imprimir.', variant: 'destructive' });
      return;
    }
    printWindow.document.write(getFullHtml());
    printWindow.document.close();
    printWindow.onafterprint = () => printWindow.close();
    setTimeout(() => printWindow.print(), 350);
  };

  const handleDownloadPdf = async () => {
    setIsDownloading(true);
    try {
      const html2pdf = (await import('html2pdf.js')).default;

      // Build content WITHOUT the fixed footer (it won't render in html2canvas)
      const wrapper = document.createElement('div');
      const styleEl = document.createElement('style');
      styleEl.textContent = A4_STYLES + `
        .running-footer { display: none !important; }
      `;
      wrapper.appendChild(styleEl);

      // Add header + content
      const contentDiv = document.createElement('div');
      contentDiv.innerHTML = `
        <main class="content">
          ${getHeaderHtml(teacherName, className, subjectName)}
          ${sanitizedContent}
        </main>
      `;
      wrapper.appendChild(contentDiv);
      document.body.appendChild(wrapper);

      const fileName = `Plano_AEP_${(subjectName || 'Aula').replace(/\s+/g, '_')}_${dateOnly.replace(/\//g, '-')}.pdf`;

      // Top margin increased to leave room for repeated header on subsequent pages
      const marginTop = 20;
      const marginBottom = 18;
      const marginLeft = 14;
      const marginRight = 14;

      const worker = html2pdf().set({
        margin: [marginTop, marginRight, marginBottom, marginLeft],
        filename: fileName,
        image: { type: 'jpeg', quality: 0.98 },
        html2canvas: { scale: 2, useCORS: true, logging: false },
        jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' },
        pagebreak: { mode: ['avoid-all', 'css', 'legacy'] },
      }).from(wrapper);

      // Use thennable to access jsPDF instance and add footer with page numbers
      await (worker.toPdf() as any).get('pdf').then((pdf: any) => {
        const totalPages = pdf.internal.getNumberOfPages();
        const pageWidth = pdf.internal.pageSize.getWidth();
        const pageHeight = pdf.internal.pageSize.getHeight();

        for (let i = 1; i <= totalPages; i++) {
          pdf.setPage(i);

          // Footer line
          pdf.setDrawColor(180, 200, 180);
          pdf.setLineWidth(0.3);
          pdf.line(marginLeft, pageHeight - 12, pageWidth - marginRight, pageHeight - 12);

          // Footer text - left
          pdf.setFontSize(7);
          pdf.setTextColor(120, 120, 120);
          pdf.text('SiGER - Sistema de Gestão Escolar Reviva', marginLeft, pageHeight - 8);

          // Footer text - center (date)
          const dateText = dateOnly;
          const dateWidth = pdf.getStringUnitWidth(dateText) * 7 / pdf.internal.scaleFactor;
          pdf.text(dateText, (pageWidth - dateWidth) / 2, pageHeight - 8);

          // Footer text - right (page number)
          const pageText = `Página ${i} de ${totalPages}`;
          const pageTextWidth = pdf.getStringUnitWidth(pageText) * 7 / pdf.internal.scaleFactor;
          pdf.text(pageText, pageWidth - marginRight - pageTextWidth, pageHeight - 8);
        }
      }).save();

      document.body.removeChild(wrapper);
      toast({ title: 'PDF descarregado', description: fileName });
    } catch (error) {
      console.error('Erro ao gerar PDF:', error);
      toast({ title: 'Erro', description: 'Não foi possível gerar o PDF. Tente imprimir em vez disso.', variant: 'destructive' });
    } finally {
      setIsDownloading(false);
    }
  };

  const handleSharePdf = async () => {
    const text = 'Plano de Aula AEP pronto para partilha em PDF. Use o ícone de download para gerar o PDF e partilhar.';
    if (navigator.share) {
      try {
        await navigator.share({ title: 'Plano de Aula AEP', text });
        return;
      } catch { /* user cancelled */ }
    }
    await navigator.clipboard.writeText(text);
    toast({ title: 'Copiado', description: 'Instrução de partilha copiada para a área de transferência.' });
  };

  const handleClose = () => {
    if (!isSaved && onClose) {
      setShowCloseConfirm(true);
    } else {
      onClose?.();
    }
  };

  const handleCloseConfirmed = () => {
    setShowCloseConfirm(false);
    onClose?.();
  };

  const handleSaveAndClose = () => {
    onSave();
    setShowCloseConfirm(false);
    // onClose will be triggered after save success by the parent
  };

  return (
    <div className="space-y-0">
      <div className="flex items-center justify-between px-4 py-2 bg-muted/50 rounded-t-lg border border-b-0 border-border">
        <p className="text-xs text-muted-foreground font-medium">Documento A4 · {dateOnly}</p>
        <div className="flex items-center gap-1">
          <Button variant="ghost" size="icon" onClick={handlePrint} title="Imprimir" className="h-8 w-8">
            <Printer className="h-4 w-4" />
          </Button>
          <Button variant="ghost" size="icon" onClick={handleDownloadPdf} disabled={isDownloading} title="Descarregar PDF" className="h-8 w-8">
            <FileDown className="h-4 w-4" />
          </Button>
          <Button variant="ghost" size="icon" onClick={handleSharePdf} title="Partilhar" className="h-8 w-8">
            <Share2 className="h-4 w-4" />
          </Button>
          <div className="w-px h-5 bg-border mx-1" />
          <Button size="sm" onClick={onSave} disabled={isSaving} className="h-8 text-xs gap-1">
            <Save className="h-3.5 w-3.5" /> Guardar
          </Button>
          {onClose && (
            <Button variant="ghost" size="icon" onClick={handleClose} title="Fechar pré-visualização" className="h-8 w-8 text-muted-foreground hover:text-destructive">
              <X className="h-4 w-4" />
            </Button>
          )}
        </div>
      </div>

      <div className="bg-white rounded-b-lg border border-border shadow-lg overflow-hidden">
        <div className="bg-gradient-to-r from-primary to-secondary px-6 py-3">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 bg-background/20 rounded-lg flex items-center justify-center shrink-0">
              <GraduationCap className="w-4 h-4 text-primary-foreground" />
            </div>
            <div className="min-w-0 flex-1">
              <h2 className="text-sm font-extrabold text-primary-foreground tracking-tight">ESCOLA REVIVA</h2>
              <p className="text-[10px] text-primary-foreground/80 font-medium">SiGER - Sistema de Gestão Escolar Reviva</p>
            </div>
            <div className="text-right hidden sm:block">
              <p className="text-[12px] font-bold text-primary-foreground">PLANO DE AULA AEP</p>
              <p className="text-[10px] text-primary-foreground/80">Abordagem Educacional por Princípios</p>
            </div>
          </div>
        </div>

        <div className="px-6 sm:px-10 py-5 sm:py-6 min-h-[500px] overflow-x-hidden">
          <div
            className="max-w-none prose prose-sm"
            style={{
              fontFamily: "'Work Sans', sans-serif",
              fontWeight: 300,
              color: 'hsl(20 14.3% 8%)',
              fontSize: '11px',
              lineHeight: 1.7,
            }}
            dangerouslySetInnerHTML={{ __html: sanitizedContent }}
          />
        </div>

        <div className="flex items-center justify-between px-6 sm:px-10 py-2 text-[10px] text-foreground/70">
          <span>SiGER - Sistema de Gestão Escolar Reviva</span>
          <span>{dateOnly}</span>
        </div>
      </div>

      <AlertDialog open={showCloseConfirm} onOpenChange={setShowCloseConfirm}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Plano não guardado</AlertDialogTitle>
            <AlertDialogDescription>
              O plano de aula ainda não foi guardado nos Arquivos. Deseja guardar antes de fechar?
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel onClick={handleCloseConfirmed}>Fechar sem guardar</AlertDialogCancel>
            <AlertDialogAction onClick={handleSaveAndClose}>Guardar e fechar</AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </div>
  );
}
