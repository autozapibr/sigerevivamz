export function LessonPlanPreview({ content, onSave, isSaving, teacherName = '', className = '', subjectName = '' }: LessonPlanPreviewProps) {
  const cleaned = cleanContent(content);
  const sanitizedContent = DOMPurify.sanitize(cleaned);

  const dateOnly = new Date().toLocaleDateString('pt-MZ', { day: '2-digit', month: '2-digit', year: 'numeric' });
  const dateTime = new Date().toLocaleString('pt-MZ', { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' });

  const getFullHtml = () => `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8" />
<title>Plano de Aula AEP - Escola Reviva</title>
<style>${A4_STYLES}</style>
</head>
<body>
  <div class="running-header">
    <span>Plano de Aula AEP - Escola Reviva</span>
    <span>${dateTime}</span>
  </div>

  <div class="running-footer">
    <span>SiGER - Sistema de Gestão Escolar Reviva</span>
    <span>${dateOnly}</span>
  </div>

  <main class="content">
    ${getHeaderHtml(teacherName, className, subjectName)}
    ${sanitizedContent}
  </main>
</body>
</html>`;

  const openPrintWindow = () => {
    const printWindow = window.open('', '_blank');
    if (!printWindow) {
      toast({ title: 'Erro', description: 'Permita pop-ups para imprimir ou descarregar PDF.', variant: 'destructive' });
      return null;
    }

    printWindow.document.write(getFullHtml());
    printWindow.document.close();
    return printWindow;
  };

  const handlePrint = () => {
    const printWindow = openPrintWindow();
    if (!printWindow) return;
    printWindow.onafterprint = () => printWindow.close();
    setTimeout(() => printWindow.print(), 350);
  };

  const handleDownloadPdf = () => {
    const printWindow = openPrintWindow();
    if (!printWindow) return;
    toast({ title: 'PDF', description: 'Na impressão, escolha "Guardar como PDF" e desactive os cabeçalhos/rodapés do navegador.' });
    setTimeout(() => printWindow.print(), 350);
  };

  const handleSharePdf = async () => {
    const text = 'Plano de Aula AEP pronto para partilha em PDF. Use o ícone de download para gerar o PDF e partilhar.';
    if (navigator.share) {
      try {
        await navigator.share({ title: 'Plano de Aula AEP', text });
        return;
      } catch {
        // user cancelled
      }
    }

    await navigator.clipboard.writeText(text);
    toast({ title: 'Copiado', description: 'Instrução de partilha copiada para a área de transferência.' });
  };

  return (
    <div className="space-y-0">
      <div className="flex items-center justify-between px-4 py-2 bg-muted/50 rounded-t-lg border border-b-0 border-border">
        <p className="text-xs text-muted-foreground font-medium">Documento A4 · {dateOnly}</p>
        <div className="flex items-center gap-1">
          <Button variant="ghost" size="icon" onClick={handlePrint} title="Imprimir" className="h-8 w-8">
            <Printer className="h-4 w-4" />
          </Button>
          <Button variant="ghost" size="icon" onClick={handleDownloadPdf} title="Descarregar PDF" className="h-8 w-8">
            <FileDown className="h-4 w-4" />
          </Button>
          <Button variant="ghost" size="icon" onClick={handleSharePdf} title="Partilhar" className="h-8 w-8">
            <Share2 className="h-4 w-4" />
          </Button>
          <div className="w-px h-5 bg-border mx-1" />
          <Button size="sm" onClick={onSave} disabled={isSaving} className="h-8 text-xs gap-1">
            <Save className="h-3.5 w-3.5" /> Guardar
          </Button>
        </div>
      </div>

      <div className="bg-white rounded-b-lg border border-border shadow-lg overflow-hidden">
        <div className="bg-gradient-to-r from-primary to-secondary px-6 py-3">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 bg-background/20 rounded-lg flex items-center justify-center shrink-0">
              <GraduationCap className="w-4 h-4 text-primary-foreground" />
            </div>
            <div className="min-w-0 flex-1">
              <h2 className="text-sm font-extrabold text-primary-foreground tracking-tight">ESCOLA REVIVA</h2>
              <p className="text-[10px] text-primary-foreground/80 font-medium">SiGER - Sistema de Gestão Escolar Reviva</p>
            </div>
            <div className="text-right hidden sm:block">
              <p className="text-[12px] font-bold text-primary-foreground">PLANO DE AULA AEP</p>
              <p className="text-[10px] text-primary-foreground/80">Abordagem Educacional por Princípios</p>
            </div>
          </div>
        </div>

        <div className="px-6 sm:px-10 py-5 sm:py-6 min-h-[500px] overflow-x-hidden">
          <div
            className="max-w-none prose prose-sm"
            style={{
              fontFamily: "'Work Sans', sans-serif",
              fontWeight: 300,
              color: 'hsl(20 14.3% 8%)',
              fontSize: '11px',
              lineHeight: 1.7,
            }}
            dangerouslySetInnerHTML={{ __html: sanitizedContent }}
          />
        </div>

        <div className="flex items-center justify-between px-6 sm:px-10 py-2 text-[10px] text-foreground/70">
          <span>SiGER - Sistema de Gestão Escolar Reviva</span>
          <span>{dateOnly}</span>
        </div>
      </div>
    </div>
  );
}
